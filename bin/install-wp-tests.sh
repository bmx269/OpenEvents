#!/usr/bin/env bash
#
# Sets up the WordPress PHPUnit test environment in .wp-tests/ without MySQL or
# Docker: a WordPress release, the matching test library from wordpress-develop,
# and the official SQLite database drop-in. Re-runnable; skips finished steps.
#
# Env: WP_VERSION (default 7.1.3), WP_TESTS_ROOT (default ./.wp-tests).
set -euo pipefail

WP_VERSION="${WP_VERSION:-7.1.3}"
ROOT="${WP_TESTS_ROOT:-$(pwd)/.wp-tests}"
CORE="$ROOT/wordpress"
DEVELOP="$ROOT/wordpress-develop"
SQLITE="$CORE/wp-content/plugins/sqlite-database-integration"

mkdir -p "$ROOT"

if [ ! -f "$CORE/wp-settings.php" ]; then
	echo "Downloading WordPress $WP_VERSION…"
	curl -sSL "https://wordpress.org/wordpress-${WP_VERSION}.tar.gz" | tar -xz -C "$ROOT"
fi

if [ ! -d "$DEVELOP/tests/phpunit/includes" ]; then
	echo "Fetching the PHPUnit test library for $WP_VERSION…"
	rm -rf "$DEVELOP"
	git clone --quiet --depth 1 --branch "$WP_VERSION" --filter=blob:none --sparse \
		https://github.com/WordPress/wordpress-develop.git "$DEVELOP"
	git -C "$DEVELOP" sparse-checkout set tests/phpunit/includes tests/phpunit/data
fi

if [ ! -s "$CORE/wp-content/db.php" ]; then
	echo "Installing the SQLite database drop-in…"
	rm -rf "$SQLITE"
	curl -sSL -o "$ROOT/sqlite.zip" https://downloads.wordpress.org/plugin/sqlite-database-integration.latest-stable.zip
	unzip -q -o "$ROOT/sqlite.zip" -d "$CORE/wp-content/plugins/"
	rm "$ROOT/sqlite.zip"
	sed -e "s#{SQLITE_IMPLEMENTATION_FOLDER_PATH}#${SQLITE}#" \
		-e "s#{SQLITE_PLUGIN}#sqlite-database-integration/load.php#" \
		"$SQLITE/db.copy" > "$CORE/wp-content/db.php.tmp"
	# Write atomically so a failed step is retried on the next run.
	mv "$CORE/wp-content/db.php.tmp" "$CORE/wp-content/db.php"
fi

cat > "$DEVELOP/wp-tests-config.php" <<PHP
<?php
// Generated by bin/install-wp-tests.sh.
define( 'ABSPATH', '${CORE}/' );
define( 'WP_DEFAULT_THEME', 'default' );
define( 'WP_DEBUG', true );
// SQLite drop-in: database file lives under .wp-tests/, MySQL constants are placeholders.
define( 'DB_DIR', '${ROOT}/database/' );
define( 'DB_FILE', 'tests.sqlite' );
define( 'DB_NAME', 'wordpress_tests' );
define( 'DB_USER', 'root' );
define( 'DB_PASSWORD', '' );
define( 'DB_HOST', 'localhost' );
define( 'DB_CHARSET', 'utf8' );
define( 'DB_COLLATE', '' );
\$table_prefix = 'wptests_';
define( 'WP_TESTS_DOMAIN', 'example.org' );
define( 'WP_TESTS_EMAIL', 'admin@example.org' );
define( 'WP_TESTS_TITLE', 'Test Blog' );
define( 'WP_PHP_BINARY', 'php' );
define( 'WPLANG', '' );
PHP

mkdir -p "$ROOT/database"
echo "Test environment ready in $ROOT"
